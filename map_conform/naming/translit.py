"""The bundled ASCII transliteration table (ADR-0012).

The table maps single characters to ASCII and is package data, so conformed names are the
same on every Python version and platform. It is generated by :func:`build_table` from

1. Unicode decompositions (NFKD with combining marks removed), taken from the Unicode
   version in :data:`UNICODE_VERSION`; and
2. :data:`SUPPLEMENT`, written for this project, for letters that do not decompose (``ß``,
   ``Ø``, ``Ł``, ...) and for Greek and Cyrillic romanisation. Nothing is copied from
   GPL-licensed tables.

Regenerate on a Python whose ``unicodedata`` has that version (3.14 has 16.0.0)::

    uv run python -m map_conform.naming.translit
"""

from __future__ import annotations

import functools
import json
import unicodedata
from pathlib import Path

UNICODE_VERSION = "16.0.0"
TABLE_PATH = Path(__file__).resolve().parent / "ascii-table.json"

RANGES: tuple[tuple[int, int, str], ...] = (
    (0x00C0, 0x00FF, "Latin-1 Supplement letters"),
    (0x0100, 0x017F, "Latin Extended-A"),
    (0x0180, 0x024F, "Latin Extended-B"),
    (0x1E00, 0x1EFF, "Latin Extended Additional"),
    (0x0370, 0x03FF, "Greek and Coptic"),
    (0x1F00, 0x1FFF, "Greek Extended"),
    (0x0400, 0x04FF, "Cyrillic"),
)

_GREEK = {
    "α": "a", "β": "v", "γ": "g", "δ": "d", "ε": "e", "ζ": "z", "η": "i", "θ": "th",
    "ι": "i", "κ": "k", "λ": "l", "μ": "m", "ν": "n", "ξ": "x", "ο": "o", "π": "p",
    "ρ": "r", "σ": "s", "ς": "s", "τ": "t", "υ": "y", "φ": "f", "χ": "ch", "ψ": "ps",
    "ω": "o",
}  # fmt: skip
_CYRILLIC = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ж": "zh", "з": "z",
    "и": "i", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh",
    "щ": "shch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    "є": "ye", "і": "i", "ґ": "g", "ђ": "dj", "ј": "j", "љ": "lj", "њ": "nj", "ћ": "c",
    "џ": "dz", "ѕ": "dz",
}  # fmt: skip
_LATIN = {
    "ß": "ss", "ẞ": "Ss", "Æ": "Ae", "æ": "ae", "Ø": "O", "ø": "o", "Œ": "Oe", "œ": "oe",
    "Đ": "D", "đ": "d", "Ð": "D", "ð": "d", "Ł": "L", "ł": "l", "Þ": "Th", "þ": "th",
    "ı": "i", "Ħ": "H", "ħ": "h", "Ŋ": "Ng", "ŋ": "ng", "Ŧ": "T", "ŧ": "t", "Ŀ": "L",
    "ŀ": "l", "ƒ": "f", "Ɖ": "D", "ɖ": "d", "Ƒ": "F",
}  # fmt: skip


def _with_capitals(lower: dict[str, str]) -> dict[str, str]:
    """Add each letter's capital, transliterated with a capital first letter."""
    table = dict(lower)
    for char, ascii_ in lower.items():
        capital = char.upper()
        if capital != char and len(capital) == 1:
            table.setdefault(capital, ascii_[:1].upper() + ascii_[1:])
    return table


SUPPLEMENT: dict[str, str] = {  # capitals in title form; see transliterate()
    **_LATIN,
    **_with_capitals(_GREEK),
    **_with_capitals(_CYRILLIC),
}
"""Hand-written mappings for characters with no ASCII decomposition."""


def _romanise(char: str) -> str | None:
    if char in SUPPLEMENT:
        return SUPPLEMENT[char]
    base = "".join(c for c in unicodedata.normalize("NFKD", char) if not unicodedata.combining(c))
    out: list[str] = []
    for c in base:
        if c.isascii():
            out.append(c)
        elif c in SUPPLEMENT:
            out.append(SUPPLEMENT[c])
        else:
            return None
    result = "".join(out)
    return result if result != char else None


def build_table() -> dict[str, str]:
    """Build the table from this interpreter's Unicode data and the supplement."""
    table: dict[str, str] = {}
    for start, end, _ in RANGES:
        for code in range(start, end + 1):
            char = chr(code)
            if not unicodedata.category(char).startswith("L"):
                continue
            ascii_ = _romanise(char)
            # Letters only: some decompositions are a space plus a mark (U+037A).
            if ascii_ is not None and (ascii_.isalpha() or (not ascii_ and char in SUPPLEMENT)):
                table[char] = ascii_
    return table


def render_table() -> str:
    """The table file's text."""
    document = {
        "unicode_version": unicodedata.unidata_version,
        "ranges": [name for _, _, name in RANGES],
        "map": dict(sorted(build_table().items())),
    }
    return json.dumps(document, ensure_ascii=False, indent=1) + "\n"


@functools.cache
def table() -> dict[str, str]:
    """The bundled table: character to ASCII string (possibly empty, e.g. the soft sign)."""
    document = json.loads(TABLE_PATH.read_text(encoding="utf-8"))
    return document["map"]


def transliterate(text: str) -> tuple[str, str]:
    """Replace non-ASCII characters using the table.

    A capital that becomes several letters is title-cased (``Θεός`` -> ``Theos``) unless a
    neighbouring letter is also a capital, when it is all caps (``ΘΕΑ`` -> ``THEA``), so
    camelCase splitting does not cut all-caps words apart.

    Returns:
        The ASCII result, and the characters that had no mapping and were dropped.
    """
    mapping = table()
    out: list[str] = []
    dropped: list[str] = []
    for i, char in enumerate(text):
        if char.isascii():
            out.append(char)
        elif char in mapping:
            ascii_ = mapping[char]
            if len(ascii_) > 1 and char.isupper() and _capital_beside(text, i):
                ascii_ = ascii_.upper()
            out.append(ascii_)
        else:
            dropped.append(char)
    return "".join(out), "".join(dropped)


def _capital_beside(text: str, i: int) -> bool:
    before = text[i - 1] if i > 0 else ""
    after = text[i + 1] if i + 1 < len(text) else ""
    return before.isupper() or after.isupper()


def main() -> int:
    """Write the bundled table."""
    if unicodedata.unidata_version != UNICODE_VERSION:
        msg = (
            f"this Python has Unicode {unicodedata.unidata_version}; the table is pinned to "
            f"{UNICODE_VERSION}. Run with a Python that has it (3.14 has 16.0.0)."
        )
        raise SystemExit(msg)
    TABLE_PATH.write_text(render_table(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
