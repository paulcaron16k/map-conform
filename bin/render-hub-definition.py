#!/usr/bin/env python3
"""Render the Meltano Hub plugin definition (WBS 10.4).

Writes ``plugin-definition.yml`` from ``meltano.yml``'s map-conform mapper (its settings) and
the mapper's own ``--about`` (its capabilities), in the shape Meltano Hub keeps under
``_data/meltano/mappers/map-conform/paulcaron16k.yml``. Until the plugin is on the Hub, a
project can paste the same block under ``plugins.mappers`` as a custom plugin.
``tests/test_hub_definition.py`` fails when the file is stale.

Usage: uv run bin/render-hub-definition.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "plugin-definition.yml"
HEADER = """\
# Meltano Hub plugin definition for map-conform. GENERATED by bin/render-hub-definition.py
# from meltano.yml and the mapper's --about; do not edit. On the Hub it is
# _data/meltano/mappers/map-conform/paulcaron16k.yml. Until then, paste it under
# plugins.mappers in a Meltano project as a custom mapper, and add a mapping:
#   mappings:
#   - name: conform
#     config: {spec_path: conform.yml}
"""


def definition() -> dict[str, Any]:
    """The Hub entry."""
    sys.path.insert(0, str(ROOT))
    from map_conform.mapper import MapConformMapper  # noqa: PLC0415 -- after the path is set

    project = yaml.safe_load((ROOT / "meltano.yml").read_text(encoding="utf-8"))
    mapper = next(m for m in project["plugins"]["mappers"] if m["name"] == "map-conform")
    capabilities = [str(c) for c in MapConformMapper.capabilities]
    return {
        "name": "map-conform",
        "namespace": "map_conform",
        "variant": "paulcaron16k",
        "label": "map-conform",
        "description": (
            "Conforms names, types, values and metadata between any tap and any target so data "
            "lands clean; a superset of SDK stream maps, with BATCH support."
        ),
        "domain_url": "https://github.com/paulcaron16k/map-conform",
        "repo": "https://github.com/paulcaron16k/map-conform",
        "pip_url": "map-conform",
        "executable": "map-conform",
        "maintenance_status": "active",
        "keywords": ["meltano_sdk"],
        "capabilities": capabilities,
        "settings_group_validation": [[]],
        "settings": mapper["settings"],
    }


def render() -> str:
    """The file's text."""
    body = yaml.safe_dump(definition(), sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def main() -> int:
    """Write plugin-definition.yml."""
    OUTPUT.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
